# Faça um algoritmo que calcule a multiplicação entre dois números
# sem utilizar o sinal de multiplicação ( * ) 
# ou função. Utilize estrutura de repetição e soma.

x = int(input("Digite um número: "))
y = int(input("Digite outro número: "))
r = 0
i = 0
while i <  x:
    r = r + y
    i = i + 1
print(r)
